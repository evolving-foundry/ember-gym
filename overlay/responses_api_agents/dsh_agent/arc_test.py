def all_zero_rects(g):
    R, C = len(g), len(g[0])
    results = []
    for r1 in range(R):
        for r2 in range(r1, R):
            c1 = None
            for c in range(C + 1):
                if c < C and all(g[r][c] == 0 for r in range(r1, r2 + 1)):
                    if c1 is None:
                        c1 = c
                else:
                    if c1 is not None:
                        results.append((r1, r2, c1, c - 1, (r2 - r1 + 1) * (c - c1)))
                        c1 = None
    return results


