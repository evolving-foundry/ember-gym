"""NPC actor engine (design §3.2 六件套): persona cards, deterministic turns.

Each npc card = persona + role + action whitelist + content mode:

- ``mode: template`` — the reply text is formatted from the card's ``template``
  (zero LLM; the §7.4 cost-degradation path);
- ``mode: llm_sim`` — the reply text is generated by the constrained simulator
  model; the *action* the NPC takes is still chosen deterministically from the
  card's ``auto_actions`` triggers. The LLM is a content generator in a cage,
  never a decision maker (状态、规则、事件全部确定性).

Turn selection is a pure function over the current state: the first
``auto_actions`` entry whose ``when`` predicate matches. The whitelist is
enforced *by the rules engine downstream* — an NPC attempting an action outside
``allowed_actions`` is recorded as an unauthorized overreach (越权必被拒), this
module only nominates.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any


@dataclass(frozen=True)
class NpcTurnRequest:
    """A deterministic NPC turn awaiting content + rules adjudication."""

    npc_id: str
    role: str
    mode: str  # "template" | "llm_sim"
    action: dict[str, Any]  # {"name": ..., "args": {...}}
    template: str  # rendered content source for template mode
    context: dict[str, Any] = field(default_factory=dict)  # llm_sim grounding inputs
    trigger: str = ""  # "action:<name>" | "event:<id>"


def _matches(obj: dict[str, Any], when: dict[str, Any]) -> bool:
    for path, expected in (when or {}).items():
        value: Any = obj
        for part in path.split("."):
            if not isinstance(value, dict) or part not in value:
                value = None
                break
            value = value[part]
        if value != expected:
            return False
    return True


class NpcEngine:
    """Nominates NPC turns from cards; content and adjudication happen downstream."""

    def __init__(self, npc_model: dict[str, Any]):
        self._npcs: dict[str, dict[str, Any]] = {
            card.get("id", f"npc_{index}"): card for index, card in enumerate((npc_model or {}).get("npcs", []))
        }

    def cards(self) -> dict[str, dict[str, Any]]:
        return dict(self._npcs)

    def get(self, npc_id: str) -> dict[str, Any]:
        return self._npcs.get(npc_id, {})

    def turns_for_action(self, state_engine: Any, action_name: str, focus: dict[str, Any]) -> list[NpcTurnRequest]:
        """NPC turns triggered by an agent action; ``focus`` is the acted-on object."""
        return self._collect(state_engine, trigger=f"action:{action_name}", focus=focus)

    def turns_for_event(self, state_engine: Any, event_id: str) -> list[NpcTurnRequest]:
        return self._collect(state_engine, trigger=f"event:{event_id}", focus={})

    def _collect(self, state_engine: Any, trigger: str, focus: dict[str, Any]) -> list[NpcTurnRequest]:
        turns = []
        for npc_id in sorted(self._npcs):
            card = self._npcs[npc_id]
            for rule in card.get("auto_actions", []):
                rule_trigger = rule.get("on", "")
                if rule_trigger and rule_trigger != trigger:
                    continue
                when = rule.get("when", {})
                collection = when.get("collection")
                if collection is None:
                    continue
                match = {k: v for k, v in when.items() if k != "collection"}
                obj = state_engine.find(collection, match)
                if obj is None:
                    continue
                action = rule.get("action") or {}
                args = {
                    key: self._substitute(value, obj)
                    for key, value in (action.get("args") or {}).items()
                }
                turns.append(
                    NpcTurnRequest(
                        npc_id=npc_id,
                        role=card.get("role", "npc"),
                        mode=card.get("mode", "template"),
                        action={"name": action.get("name", "comment"), "args": args},
                        template=card.get("template", ""),
                        context={"collection": collection, "object": obj},
                        trigger=trigger,
                    )
                )
                break  # one turn per card per trigger
        return turns

    @staticmethod
    def _substitute(value: Any, obj: dict[str, Any]) -> Any:
        """Expand ``"{obj.field}"`` placeholders in action args (deterministic)."""
        if isinstance(value, str) and value.startswith("{obj.") and value.endswith("}"):
            path = value[5:-1]
            current: Any = obj
            for part in path.split("."):
                if not isinstance(current, dict) or part not in current:
                    return value
                current = current[part]
            return current
        return value
